'use strict';

/**
 * Run this BEFORE building the .exe (npm run dist:win already does
 * this for you automatically - see the "predist:win" script in
 * package.json).
 *
 * It reads POS_MASTER_SECRET from your current terminal session and
 * writes it into electron/security/master-secret.generated.js as a
 * plain string. That file then gets bundled into the packaged app,
 * which is the only way the secret can survive into a customer's
 * installed .exe (a customer's PC will never have your shell's
 * environment variables).
 *
 * Usage (macOS/Linux):
 *   POS_MASTER_SECRET="something-long-and-random" npm run dist:win
 *
 * Usage (Windows PowerShell):
 *   $env:POS_MASTER_SECRET="something-long-and-random"
 *   npm run dist:win
 *
 * Full step-by-step walkthrough: docs/MASTER_KEY_AND_BUILD_GUIDE.md
 */

const fs = require('fs');
const path = require('path');

const OUTPUT_PATH = path.join(__dirname, '..', 'electron', 'security', 'master-secret.generated.js');
const MIN_LENGTH = 16;

function main() {
  const secret = (process.env.POS_MASTER_SECRET || '').trim();

  if (!secret) {
    console.warn('\n' + '='.repeat(70));
    console.warn('[master-secret] POS_MASTER_SECRET is not set.');
    console.warn('[master-secret] The build will continue, but the packaged app');
    console.warn('[master-secret] will fall back to an INSECURE dev secret - anyone');
    console.warn('[master-secret] could compute valid master recovery keys.');
    console.warn('[master-secret] See docs/MASTER_KEY_AND_BUILD_GUIDE.md before shipping.');
    console.warn('='.repeat(70) + '\n');
    return; // leave the existing generated file (placeholder or previous real one) untouched
  }

  if (secret.length < MIN_LENGTH) {
    console.error(`[master-secret] POS_MASTER_SECRET must be at least ${MIN_LENGTH} characters. Aborting build.`);
    process.exit(1);
  }

  const fileContents = `'use strict';

// AUTO-GENERATED by scripts/generate-master-secret-file.js - DO NOT COMMIT THIS FILE.
// Regenerate any time by setting POS_MASTER_SECRET and re-running the build.
module.exports = {
  MASTER_SECRET: ${JSON.stringify(secret)},
};
`;

  fs.writeFileSync(OUTPUT_PATH, fileContents, 'utf8');
  console.log(`[master-secret] Wrote a real secret (${secret.length} chars) into ${path.relative(process.cwd(), OUTPUT_PATH)}`);
  console.log('[master-secret] Reminder: keep this exact secret written down somewhere safe (e.g. a password manager).');
  console.log('[master-secret] You will need the SAME secret every time you run scripts/compute-master-key.js for a customer.');
}

main();
